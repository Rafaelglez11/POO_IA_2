public class OperacionMatematica {

    public static void main(String[] args) {

        // Declaración + asignación (expresión)
        int producto = 8 * 12;

        // Declaración
        int cociente;

        // Asignación
        cociente = 20 / 4;

        System.out.println("El producto es: " + producto);
        System.out.println("El cociente es: " + cociente);
    }
}